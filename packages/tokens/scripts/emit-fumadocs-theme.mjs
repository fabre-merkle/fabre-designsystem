#!/usr/bin/env node
/**
 * emit-fumadocs-theme.mjs — turn the exported `semantic-fumadocs` set into an
 * `@theme` file Tailwind v4 can generate utilities from.
 *
 * The CSS export format has no per-set filter and `wrapInTheme` wraps the WHOLE
 * document (every set), not one set — so there is no saved export preset that
 * emits just the Fumadocs `--color-fd-*` map as `@theme { … }`. What
 * DOES scope correctly is the plain `css` export's split layout: it isolates
 * every token set into its own file, so `studio exports run css --out ./css/`
 * already writes `css/semantic-fumadocs/default.css` containing ONLY the fd
 * vars — as a `@layer { :root { … } }` block, not `@theme`. This script re-wraps
 * that isolated file's `--color-fd-*` declarations in `@theme { … }` and writes
 * `semantic-fumadocs/theme.css` — the shape `docs-fumadocs-core`'s globals.css
 * imports (`@import "@fabre-designsystem/tokens/css/semantic-fumadocs/theme.css"`). The
 * `var(--theme-color-*)` references inside are left untouched, so the map stays
 * theme-aware.
 *
 * Run after `studio exports run css --out ./css/` (wired into
 * `tokens:studio:exports` via `studio-exports-setup.ts`). Idempotent: a dir that
 * already has only `theme.css` is left untouched.
 *
 * Usage: node scripts/emit-fumadocs-theme.mjs <css-dir>
 *   e.g. node scripts/emit-fumadocs-theme.mjs ./css
 */
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("Usage: emit-fumadocs-theme.mjs <css-dir>");
  process.exit(1);
}

function toThemeBlock(text) {
  const decls = [...text.matchAll(/(--color-fd-[a-z0-9-]+)\s*:\s*([^;]+);/gi)].map(
    ([, name, value]) => `  ${name}: ${value.trim()};`,
  );
  if (decls.length === 0) return null;
  return [
    "/*! Fumadocs (Base UI) fd theme.",
    " * The Fumadocs surface map as an @theme block, so Tailwind generates the",
    " * bg-fd / text-fd utilities its components use (a plain @layer{:root} sets",
    " * the values but can't emit utilities). Re-wrapped from the Tokens Studio",
    " * semantic-fumadocs set; var(--theme-color-*) refs keep it theme-aware.",
    " * Auto-generated by tokens:studio:exports; do not edit. */",
    "@theme {",
    ...decls,
    "}",
    "",
  ].join("\n");
}

const abs = resolve(process.cwd(), dir);
const defaultCss = resolve(abs, "semantic-fumadocs/default.css");
const themeCss = resolve(abs, "semantic-fumadocs/theme.css");

if (!existsSync(defaultCss)) {
  if (existsSync(themeCss)) {
    console.log(`✓ ${dir}: semantic-fumadocs/theme.css already in place`);
    process.exit(0);
  }
  console.error(`✗ ${dir}: no semantic-fumadocs/default.css or theme.css.`);
  process.exit(1);
}

const block = toThemeBlock(readFileSync(defaultCss, "utf8"));
if (block === null) {
  console.error(`✗ ${dir}: no --color-fd-* declarations in default.css.`);
  process.exit(1);
}
writeFileSync(themeCss, block);
rmSync(defaultCss);
console.log(`✓ ${dir}: semantic-fumadocs/theme.css (from default.css)`);
